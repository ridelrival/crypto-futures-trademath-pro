  const languages = [
    { code: "en", name: "English", native: "English", group: "primary" },
    { code: "id", name: "Indonesian", native: "Bahasa Indonesia", group: "primary" },
    { code: "ja", name: "Japanese", native: "日本語", group: "primary" },
  ];

  const dictionaries = { en, id, ja };
  let active = localStorage.getItem("trademath-language") || "en";
  if (!languages.some((language) => language.code === active)) active = "en";

  function format(template, variables) {
    return Object.entries(variables || {}).reduce(
      (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
      template,
    );
  }

  function t(key, variables) {
    const dictionary = dictionaries[active] || en;
    return format(dictionary[key] || en[key] || key, variables);
  }

  function apply() {
    const dictionary = dictionaries[active] || en;
    document.documentElement.lang = active;
    document.documentElement.dir = active === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      element.textContent = dictionary[key] || en[key] || element.textContent;
    });
    const search = document.getElementById("languageSearch");
    if (search) search.placeholder = dictionary.searchLanguages || en.searchLanguages;
    const badge = document.getElementById("activeLanguage");
    if (badge) badge.textContent = active.toUpperCase();
    document.dispatchEvent(new CustomEvent("trademath:languagechange", { detail: { language: active } }));
  }

  function setLanguage(code) {
    if (!languages.some((language) => language.code === code)) return;
    active = code;
    localStorage.setItem("trademath-language", active);
    apply();
  }

  window.TradeMathI18n = {
    t,
    apply,
    setLanguage,
    getLanguage: () => active,
    languages,
    isFullTranslation: (code) => Boolean(dictionaries[code]),
  };
